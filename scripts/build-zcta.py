#!/usr/bin/env python3
"""Rebuild data/zcta-centroids.tsv.gz from a Census ZCTA Gazetteer national file.

The official file is public domain (17 U.S.C. § 105). Download, for example:

  curl -L -O https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2025_Gazetteer/2025_Gaz_zcta_national.zip

Then:

  python3 scripts/build-zcta.py /path/to/2025_Gaz_zcta_national.txt
"""

from __future__ import annotations

import argparse
import gzip
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEST = ROOT / "data" / "zcta-centroids.tsv.gz"

HEADER = """# US Census Bureau 2025 ZCTA Gazetteer internal points (GEOID, INTPTLAT, INTPTLONG).
# US Government work, public domain (17 U.S.C. § 105). Cite the U.S. Census Bureau as the source.
# This software is not affiliated with or endorsed by the Census Bureau.
# Source: https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2025_Gazetteer/2025_Gaz_zcta_national.zip
# Regenerated by scripts/build-zcta.py. ZCTAs are not identical to every USPS ZIP code.
zip\tlat\tlon
"""


def main() -> int:
    parser = argparse.ArgumentParser(description="Build the bundled ZCTA centroid table")
    parser.add_argument("gazetteer")
    parser.add_argument("--out", default=str(DEST))
    args = parser.parse_args()
    src = Path(args.gazetteer)
    text = src.read_text(encoding="utf-8")
    lines = text.splitlines()
    if not lines:
        raise SystemExit("Gazetteer file is empty")
    header = lines[0].split("|")
    if header[0] != "GEOID" or header[-2] != "INTPTLAT" or header[-1] != "INTPTLONG":
        raise SystemExit(f"Unexpected gazetteer columns: {header}")
    rows: list[tuple[str, float, float]] = []
    for line in lines[1:]:
        if not line.strip():
            continue
        parts = line.split("|")
        zip_code = parts[0].strip()
        if len(zip_code) != 5 or not zip_code.isdigit():
            raise SystemExit(f"Unexpected GEOID: {zip_code!r}")
        rows.append((zip_code, round(float(parts[-2]), 4), round(float(parts[-1]), 4)))
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with gzip.open(out, "wt", encoding="utf-8", newline="\n") as handle:
        handle.write(HEADER)
        for zip_code, lat, lon in rows:
            handle.write(f"{zip_code}\t{lat:.4f}\t{lon:.4f}\n")
    print(f"Wrote {out} ({len(rows)} ZCTAs)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
